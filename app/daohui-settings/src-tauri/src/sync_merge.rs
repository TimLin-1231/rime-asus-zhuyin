//! The merges of a sync run as pure functions (no I/O), see SYNC.md.
//!
//! - personal words: union, the larger weight wins;
//! - e-mail addresses: union of lines;
//! - shortcuts: per abbreviation the newest change wins (deletions too);
//! - settings: per key the newest change wins.
//!
//! Every merge is idempotent (merging the same input again changes nothing)
//! and does not depend on the order in which devices are merged.

use std::collections::{BTreeMap, BTreeSet};

use serde::{Deserialize, Serialize};

/// Unix time in seconds.
pub type Time = i64;

// ------------------------------------------------------------ personal words

/// One entry of a Rime dictionary: `text<TAB>code<TAB>weight`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Word {
    pub text: String,
    /// Pinyin syllables separated by single spaces.
    pub code: String,
    pub weight: Option<i64>,
}

fn parse_word_line(line: &str) -> Option<Word> {
    let line = line.strip_suffix('\r').unwrap_or(line);
    if line.trim().is_empty() || line.starts_with('#') {
        return None;
    }
    let mut cols = line.split('\t');
    let text = cols.next()?.trim();
    let code = cols.next()?.split_whitespace().collect::<Vec<_>>().join(" ");
    if text.is_empty() || code.is_empty() {
        return None;
    }
    let weight = cols
        .next()
        .and_then(|w| w.trim().parse::<f64>().ok())
        .filter(|w| w.is_finite())
        .map(|w| w.round() as i64);
    Some(Word { text: text.to_string(), code, weight })
}

/// Lines of `word<TAB>pinyin<TAB>weight` (the sync folder's personal.txt).
pub fn parse_words(text: &str) -> Vec<Word> {
    text.trim_start_matches('\u{feff}').lines().filter_map(parse_word_line).collect()
}

/// The entries of a `*.dict.yaml`: the lines after the header's `...`.
pub fn parse_dict(text: &str) -> Vec<Word> {
    let mut lines = text.trim_start_matches('\u{feff}').lines();
    if !lines.any(|l| l.trim_end() == "...") {
        return Vec::new();
    }
    lines.filter_map(parse_word_line).collect()
}

pub fn render_words(words: &[Word]) -> String {
    let mut s = String::new();
    for w in words {
        s.push_str(&w.text);
        s.push('\t');
        s.push_str(&w.code);
        if let Some(n) = w.weight {
            s.push('\t');
            s.push_str(&n.to_string());
        }
        s.push('\n');
    }
    s
}

/// Header of the user dir's `terra_pinyin.synced.dict.yaml`, which
/// `terra_pinyin.asus.dict.yaml` imports.
pub const SYNCED_DICT_HEADER: &str = "# Rime dictionary
# encoding: utf-8
#
# 島輝同步：從其他裝置同步來的個人詞。
# GENERATED by DaoHuiSettings --sync from <sync_dir>/daohui/*/personal.txt -- do not edit.
# Words of this device are in terra_pinyin.personal.dict.yaml.
---
name: terra_pinyin.synced
version: \"1\"
sort: by_weight
use_preset_vocabulary: false
...

";

pub fn render_synced_dict(words: &[Word]) -> String {
    format!("{SYNCED_DICT_HEADER}{}", render_words(words))
}

/// Union of word lists, one entry per (text, code) with the larger weight,
/// sorted by (text, code).
pub fn union_words(lists: &[&[Word]]) -> Vec<Word> {
    let mut map: BTreeMap<(String, String), Option<i64>> = BTreeMap::new();
    for list in lists {
        for w in *list {
            let slot = map.entry((w.text.clone(), w.code.clone())).or_insert(None);
            *slot = (*slot).max(w.weight);
        }
    }
    map.into_iter().map(|((text, code), weight)| Word { text, code, weight }).collect()
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PersonalMerge {
    /// New content of terra_pinyin.synced.dict.yaml: the other devices'
    /// words that are not this device's own.
    pub synced: Vec<Word>,
    /// This device's personal.txt: own ∪ synced.
    pub export: Vec<Word>,
}

pub fn merge_personal(own: &[Word], synced: &[Word], others: &[Vec<Word>]) -> PersonalMerge {
    let own_keys: BTreeSet<(&str, &str)> = own.iter().map(|w| (w.text.as_str(), w.code.as_str())).collect();
    let mut lists: Vec<&[Word]> = vec![synced];
    lists.extend(others.iter().map(|v| v.as_slice()));
    let synced: Vec<Word> = union_words(&lists)
        .into_iter()
        .filter(|w| !own_keys.contains(&(w.text.as_str(), w.code.as_str())))
        .collect();
    let export = union_words(&[own, synced.as_slice()]);
    PersonalMerge { synced, export }
}

// ------------------------------------------------------------ e-mail addresses

/// Addresses of an emails.txt: trimmed lines, no comments, case-insensitively
/// unique (the first spelling is kept).
pub fn parse_emails(text: &str) -> Vec<String> {
    let mut seen = BTreeSet::new();
    text.trim_start_matches('\u{feff}')
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#') && l.contains('@') && !l.contains(char::is_whitespace))
        .filter(|l| seen.insert(l.to_lowercase()))
        .map(str::to_string)
        .collect()
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EmailMerge {
    /// New text of the user dir's emails.txt, or None if unchanged.
    pub local: Option<String>,
    /// This device's emails.txt in the sync folder: one address per line.
    pub export: String,
}

fn eol_of(text: &str) -> &'static str {
    if text.contains("\r\n") {
        "\r\n"
    } else {
        "\n"
    }
}

/// `lines` appended to `text` (which keeps its own lines and line endings).
fn append_lines(text: &str, lines: &[String]) -> String {
    let eol = eol_of(text);
    let mut out = text.to_string();
    if !out.is_empty() && !out.ends_with('\n') {
        out.push_str(eol);
    }
    for l in lines {
        out.push_str(l);
        out.push_str(eol);
    }
    out
}

/// The local file keeps its lines; addresses only the other devices have
/// are appended (sorted).
pub fn merge_emails(local: Option<&str>, others: &[Vec<String>]) -> EmailMerge {
    let local_text = local.unwrap_or("");
    let mut all = parse_emails(local_text);
    let seen: BTreeSet<String> = all.iter().map(|e| e.to_lowercase()).collect();
    let mut new: BTreeMap<String, String> = BTreeMap::new();
    for list in others {
        for e in list {
            let k = e.to_lowercase();
            if !seen.contains(&k) {
                // The smallest spelling, so the result does not depend on order.
                let slot = new.entry(k).or_insert_with(|| e.clone());
                if e < slot {
                    *slot = e.clone();
                }
            }
        }
    }
    let added: Vec<String> = new.into_values().collect();
    let local = (!added.is_empty()).then(|| append_lines(local_text, &added));
    all.extend(added);
    let export = all.iter().map(|e| format!("{e}\n")).collect();
    EmailMerge { local, export }
}

// ------------------------------------------------------------ stamps

/// A value with the time it was last changed (or deleted).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Stamp {
    pub value: String,
    pub time: Time,
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub deleted: bool,
}

impl Stamp {
    pub fn new(value: impl Into<String>, time: Time) -> Self {
        Stamp { value: value.into(), time, deleted: false }
    }

    fn tombstone(time: Time) -> Self {
        Stamp { value: String::new(), time, deleted: true }
    }

    /// Newest wins; at the same time a value beats a deletion, then the
    /// larger value: a total order, so every device picks the same winner.
    fn beats(&self, other: &Stamp) -> bool {
        (self.time, !self.deleted, &self.value) > (other.time, !other.deleted, &other.value)
    }
}

/// The local value's stamp: unchanged since the last sync keeps the time it
/// had then; changed since (or deleted) gets the file's modification time,
/// and at least one second more than before; first seen gets `first_time`.
fn local_stamp(value: &str, prev: Option<&Stamp>, mtime: Time, first_time: Time) -> Stamp {
    match prev {
        Some(p) if !p.deleted && p.value == value => p.clone(),
        Some(p) => Stamp::new(value, mtime.max(p.time + 1)),
        None => Stamp::new(value, first_time),
    }
}

// ------------------------------------------------------------ shortcuts

/// Abbreviation as asus_shortcuts.lua compares it (spaces removed).
pub fn shortcut_key(abbr: &str) -> String {
    abbr.chars().filter(|c| *c != ' ' && *c != '\u{3000}').collect()
}

/// `abbreviation<TAB>expansion`, as asus_shortcuts.lua reads it.
fn parse_shortcut_line(line: &str) -> Option<(String, String)> {
    let line = line.strip_suffix('\r').unwrap_or(line);
    if line.starts_with('#') {
        return None;
    }
    let (abbr, text) = line.split_once('\t')?;
    if abbr.is_empty() || text.is_empty() || shortcut_key(abbr).is_empty() {
        return None;
    }
    Some((abbr.to_string(), text.to_string()))
}

/// Entries per abbreviation key: (abbreviation as written, expansion), in
/// file order (an abbreviation may have several expansions).
pub type ShortcutEntries = BTreeMap<String, Vec<(String, String)>>;

pub fn parse_shortcuts(text: &str) -> ShortcutEntries {
    let mut map = ShortcutEntries::new();
    for line in text.trim_start_matches('\u{feff}').lines() {
        if let Some((abbr, exp)) = parse_shortcut_line(line) {
            map.entry(shortcut_key(&abbr)).or_default().push((abbr, exp));
        }
    }
    map
}

fn shortcut_value(list: &[(String, String)]) -> String {
    list.iter().map(|(_, t)| t.as_str()).collect::<Vec<_>>().join("\n")
}

/// Prefix of the stamp lines at the end of an exported shortcuts.txt:
/// `#daohui-sync<TAB>key<TAB>time[<TAB>deleted]` (comments to the IME).
const STAMP_LINE: &str = "#daohui-sync\t";
const STAMP_INTRO: &str = "# 島輝同步：每個縮寫最後修改的時間（由同步程式維護）";

/// Another device's exported shortcuts.txt.
#[derive(Debug, Clone, Default)]
pub struct RemoteShortcuts {
    pub entries: ShortcutEntries,
    pub stamps: BTreeMap<String, Stamp>,
}

/// `file_time` stands in for entries without a stamp line (a file copied
/// by hand).
pub fn remote_shortcuts(text: &str, file_time: Time) -> RemoteShortcuts {
    let entries = parse_shortcuts(text);
    let mut times: BTreeMap<String, (Time, bool)> = BTreeMap::new();
    for line in text.lines() {
        let Some(rest) = line.strip_suffix('\r').unwrap_or(line).strip_prefix(STAMP_LINE) else { continue };
        let cols: Vec<&str> = rest.split('\t').collect();
        if let (Some(k), Some(t)) = (cols.first(), cols.get(1).and_then(|t| t.parse::<Time>().ok())) {
            times.insert(k.to_string(), (t, cols.get(2) == Some(&"deleted")));
        }
    }
    let mut stamps = BTreeMap::new();
    for (k, list) in &entries {
        let t = times.get(k).map(|(t, _)| *t).unwrap_or(file_time);
        stamps.insert(k.clone(), Stamp::new(shortcut_value(list), t));
    }
    for (k, (t, deleted)) in times {
        if deleted && !entries.contains_key(&k) {
            stamps.insert(k, Stamp::tombstone(t));
        }
    }
    RemoteShortcuts { entries, stamps }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ShortcutMerge {
    /// New text of the user dir's shortcuts.txt, or None if unchanged.
    pub local: Option<String>,
    /// This device's shortcuts.txt in the sync folder: the local file as is,
    /// then the stamp lines.
    pub export: String,
    /// Stamps to remember for the next run.
    pub state: BTreeMap<String, Stamp>,
}

/// `local`: the user dir's shortcuts.txt (None if there is none: then
/// nothing counts as deleted here); `mtime`: its modification time;
/// `state`: the stamps of the last run.
pub fn merge_shortcuts(
    local: Option<&str>,
    mtime: Time,
    state: &BTreeMap<String, Stamp>,
    remotes: &[RemoteShortcuts],
) -> ShortcutMerge {
    let text = local.unwrap_or("");
    let entries = parse_shortcuts(text);

    // Stamps of this device.
    let mut winners: BTreeMap<String, (Stamp, Option<usize>)> = BTreeMap::new();
    for (k, list) in &entries {
        winners.insert(k.clone(), (local_stamp(&shortcut_value(list), state.get(k), mtime, mtime), None));
    }
    for (k, prev) in state {
        if entries.contains_key(k) {
            continue;
        }
        if prev.deleted {
            winners.insert(k.clone(), (prev.clone(), None));
        } else if local.is_some() {
            winners.insert(k.clone(), (Stamp::tombstone(mtime.max(prev.time + 1)), None));
        }
    }
    for (i, r) in remotes.iter().enumerate() {
        for (k, s) in &r.stamps {
            match winners.get(k) {
                Some((cur, _)) if !s.beats(cur) => {}
                _ => {
                    winners.insert(k.clone(), (s.clone(), Some(i)));
                }
            }
        }
    }

    // The local file with the winners applied: its own lines stay where
    // they are, changed abbreviations are replaced in place, new ones are
    // appended.
    let eol = eol_of(text);
    let remote_lines = |k: &str, i: usize| -> Vec<String> {
        remotes[i].entries.get(k).map(|l| l.iter().map(|(a, t)| format!("{a}\t{t}")).collect()).unwrap_or_default()
    };
    let mut out: Vec<String> = Vec::new();
    let mut replaced = BTreeSet::new();
    let body = text.strip_prefix('\u{feff}').unwrap_or(text);
    for line in body.lines() {
        let line = line.strip_suffix('\r').unwrap_or(line);
        let Some((abbr, _)) = parse_shortcut_line(line) else {
            out.push(line.to_string());
            continue;
        };
        let k = shortcut_key(&abbr);
        match &winners[&k] {
            (_, None) => out.push(line.to_string()),
            (s, Some(_)) if s.deleted => {}
            (s, Some(_)) if s.value == shortcut_value(&entries[&k]) => out.push(line.to_string()),
            (_, Some(i)) => {
                if replaced.insert(k.clone()) {
                    out.extend(remote_lines(&k, *i));
                }
            }
        }
    }
    let mut added = Vec::new();
    for (k, (s, src)) in &winners {
        if let (false, Some(i), false) = (s.deleted, src, entries.contains_key(k)) {
            added.extend(remote_lines(k, *i));
        }
    }
    let mut new_text = String::new();
    if body.len() != text.len() {
        new_text.push('\u{feff}');
    }
    new_text.push_str(&out.join(eol));
    if !out.is_empty() && (body.ends_with('\n') || !added.is_empty()) {
        new_text.push_str(eol);
    }
    for l in &added {
        new_text.push_str(l);
        new_text.push_str(eol);
    }

    let state: BTreeMap<String, Stamp> = winners.into_iter().map(|(k, (s, _))| (k, s)).collect();
    let mut export = new_text.clone();
    if !export.is_empty() && !export.ends_with('\n') {
        export.push_str(eol);
    }
    if !state.is_empty() {
        export.push_str(STAMP_INTRO);
        export.push_str(eol);
        for (k, s) in &state {
            export.push_str(&format!("{STAMP_LINE}{k}\t{}{}{eol}", s.time, if s.deleted { "\tdeleted" } else { "" }));
        }
    }
    let local = (new_text != text && !(local.is_none() && new_text.is_empty())).then_some(new_text);
    ShortcutMerge { local, export, state }
}

// ------------------------------------------------------------ settings

/// `key<TAB>value<TAB>time` lines (the sync folder's settings.txt).
pub fn parse_settings(text: &str) -> BTreeMap<String, Stamp> {
    let mut map = BTreeMap::new();
    for line in text.lines() {
        let cols: Vec<&str> = line.trim_end_matches('\r').split('\t').collect();
        if let [k, v, t, ..] = cols[..] {
            if let Ok(t) = t.parse::<Time>() {
                if !k.is_empty() && !k.starts_with('#') {
                    map.insert(k.to_string(), Stamp::new(v, t));
                }
            }
        }
    }
    map
}

pub fn render_settings(stamps: &BTreeMap<String, Stamp>) -> String {
    stamps.iter().map(|(k, s)| format!("{k}\t{}\t{}\n", s.value, s.time)).collect()
}

/// Stamps of this device's settings. `explicit`: keys written in the patch
/// file; a key first seen at its default value gets time 0, so any value
/// set on another device wins over it.
pub fn local_setting_stamps(
    values: &BTreeMap<String, String>,
    explicit: &BTreeSet<String>,
    mtime: Time,
    state: &BTreeMap<String, Stamp>,
) -> BTreeMap<String, Stamp> {
    values
        .iter()
        .map(|(k, v)| {
            let first = if explicit.contains(k) { mtime } else { 0 };
            (k.clone(), local_stamp(v, state.get(k), mtime, first))
        })
        .collect()
}

/// Per key of `local` the newest stamp among this and the other devices;
/// values that `valid` rejects are ignored.
pub fn merge_settings(
    local: &BTreeMap<String, Stamp>,
    remotes: &[BTreeMap<String, Stamp>],
    valid: impl Fn(&str, &str) -> bool,
) -> BTreeMap<String, Stamp> {
    let mut out = local.clone();
    for r in remotes {
        for (k, s) in r {
            if let Some(cur) = out.get_mut(k) {
                if valid(k, &s.value) && s.beats(cur) {
                    *cur = s.clone();
                }
            }
        }
    }
    out
}

// ------------------------------------------------------------ devices

/// device.txt: `installation_id<TAB>OS<TAB>hostname<TAB>last sync<TAB>app version`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Device {
    pub id: String,
    pub os: String,
    pub host: String,
    pub time: Time,
    pub version: String,
}

fn field(s: &str) -> String {
    s.replace(['\t', '\r', '\n'], " ").trim().to_string()
}

pub fn render_device(d: &Device) -> String {
    format!("{}\t{}\t{}\t{}\t{}\n", field(&d.id), field(&d.os), field(&d.host), d.time, field(&d.version))
}

pub fn parse_device(text: &str) -> Option<Device> {
    let line = text.trim_start_matches('\u{feff}').lines().find(|l| !l.trim().is_empty())?;
    let cols: Vec<&str> = line.trim_end_matches('\r').split('\t').collect();
    let id = cols.first()?.trim();
    if id.is_empty() {
        return None;
    }
    Some(Device {
        id: id.to_string(),
        os: cols.get(1).unwrap_or(&"").trim().to_string(),
        host: cols.get(2).unwrap_or(&"").trim().to_string(),
        time: cols.get(3).and_then(|t| t.trim().parse().ok()).unwrap_or(0),
        version: cols.get(4).unwrap_or(&"").trim().to_string(),
    })
}


    #[test]
    fn shortcuts_newest_per_abbreviation() {
        // PC: two entries, synced at t=100 (state), then ㄒㄒ edited at 200.
        let pc_text = "# 快捷文字\nㄉㄓ\t台北市\nㄒㄒ\t謝謝您\n";
        let mut state = BTreeMap::new();
        state.insert("ㄉㄓ".to_string(), Stamp::new("台北市", 100));
        state.insert("ㄒㄒ".to_string(), Stamp::new("謝謝", 100));
        // Mac: changed ㄉㄓ at 150, ㄒㄒ unchanged since 100, added ㄒㄏ at 150.
        let mac = sc(
            "ㄒㄒ\t謝謝\nㄉ ㄓ\t新北市\nㄒㄏ\t此致\\n敬禮\n#daohui-sync\tㄉㄓ\t150\n#daohui-sync\tㄒㄒ\t100\n#daohui-sync\tㄒㄏ\t150\n",
            999,
        );
        let m = merge_shortcuts(Some(pc_text), 200, &state, &[mac.clone()]);
        assert_eq!(m.local.as_deref(), Some("# 快捷文字\nㄉ ㄓ\t新北市\nㄒㄒ\t謝謝您\nㄒㄏ\t此致\\n敬禮\n"));
        assert_eq!(m.state["ㄉㄓ"], Stamp::new("新北市", 150));
        assert_eq!(m.state["ㄒㄒ"], Stamp::new("謝謝您", 200));
        assert!(m.export.starts_with(m.local.as_deref().unwrap()));
        assert!(m.export.contains("#daohui-sync\tㄒㄒ\t200\n"));

        // Idempotent: the same input again (the file now newer) changes nothing.
        let again = merge_shortcuts(m.local.as_deref(), 300, &m.state, &[mac]);
        assert_eq!(again.local, None);
        assert_eq!(again.state, m.state);
        assert_eq!(again.export, m.export);

        // The Mac merges the PC's export: both end with the same entries.
        let mac_state: BTreeMap<String, Stamp> =
            [("ㄉㄓ", "新北市", 150), ("ㄒㄒ", "謝謝", 100), ("ㄒㄏ", "此致\\n敬禮", 150)]
                .iter()
                .map(|(k, v, t)| (k.to_string(), Stamp::new(*v, *t)))
                .collect();
        let mac_text = "ㄒㄒ\t謝謝\nㄉ ㄓ\t新北市\nㄒㄏ\t此致\\n敬禮\n";
        let mm = merge_shortcuts(Some(mac_text), 160, &mac_state, &[sc(&m.export, 0)]);
        assert_eq!(mm.local.as_deref(), Some("ㄒㄒ\t謝謝您\nㄉ ㄓ\t新北市\nㄒㄏ\t此致\\n敬禮\n"));
        assert_eq!(mm.state, m.state);
    }

    #[test]
    fn shortcut_deletion_wins_when_newer() {
        let state: BTreeMap<String, Stamp> =
            [("ㄅ".to_string(), Stamp::new("一", 100)), ("ㄆ".to_string(), Stamp::new("二", 100))].into();
        // Deleted ㄆ locally (file changed at 200).
        let m = merge_shortcuts(Some("ㄅ\t一\n"), 200, &state, &[sc("ㄅ\t一\nㄆ\t二\n#daohui-sync\tㄅ\t100\n#daohui-sync\tㄆ\t100\n", 0)]);
        assert_eq!(m.local, None);
        assert!(m.state["ㄆ"].deleted);
        assert!(m.export.contains("#daohui-sync\tㄆ\t200\tdeleted\n"));
        // The other device applies the deletion...
        let other_state = state.clone();
        let o = merge_shortcuts(Some("ㄅ\t一\nㄆ\t二\n"), 150, &other_state, &[sc(&m.export, 0)]);
        assert_eq!(o.local.as_deref(), Some("ㄅ\t一\n"));
        assert_eq!(o.state, m.state);
        // ...but a newer re-add elsewhere beats the deletion.
        let readd = merge_shortcuts(Some("ㄅ\t一\n"), 300, &m.state, &[sc("ㄆ\t三\n#daohui-sync\tㄆ\t250\n", 0)]);
        assert_eq!(readd.local.as_deref(), Some("ㄅ\t一\nㄆ\t三\n"));
        // No local file: nothing is deleted, everything comes from the others.
        let fresh = merge_shortcuts(None, 0, &BTreeMap::new(), &[sc("ㄅ\t一\n", 5)]);
        assert_eq!(fresh.local.as_deref(), Some("ㄅ\t一\n"));
        assert_eq!(merge_shortcuts(None, 0, &BTreeMap::new(), &[]).local, None);
    }


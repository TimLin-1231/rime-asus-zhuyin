-- asus_keys.lua
-- Key handling for the ASUS-style Zhuyin schema (asus_zhuyin).
--
--   * Ctrl+Space toggles ascii_mode (double-tap Shift does too, in
--     asus_shift.lua). What is being typed is committed first.
--   * Shift+letter types a capital letter (English, see asus_lang.lua).
--   * Space right after an English word commits the input plus that space.
--   * BackSpace removes a whole completed syllable (one character).
--   * Compact menu (see asus_compact.lua): Down expands the full candidate
--     list. While expanded, Left/Right move the highlight, Up/Down change
--     page, 1-9 select on the current page, Space picks the highlighted
--     candidate, Enter picks it and commits everything, and Esc collapses
--     back to the compact bubble. A pick that completes the input is
--     committed at once (no Enter needed).

local kRejected, kAccepted, kNoop = 0, 1, 2

local XK_space = 0x20
local XK_Shift_L, XK_Shift_R = 0xffe1, 0xffe2
local XK_Control_L, XK_Control_R = 0xffe3, 0xffe4
local XK_Escape = 0xff1b
local XK_Down = 0xff54
local XK_Left, XK_Right, XK_Up = 0xff51, 0xff53, 0xff52
local XK_Page_Up, XK_Page_Down = 0xff55, 0xff56
local XK_BackSpace = 0xff08
local XK_Return = 0xff0d

local zy = require("asus_zhuyin_data")  -- generated by tools/build_lang_data.py
local MAX_SYLLABLE = 5

-- Keys that browse the expanded menu without collapsing it.
local NAV_KEYS = {
  [0xff50] = true, -- Home
  [0xff51] = true, -- Left
  [0xff52] = true, -- Up
  [0xff53] = true, -- Right
  [0xff54] = true, -- Down
  [0xff55] = true, -- Page_Up
  [0xff56] = true, -- Page_Down
  [0xff57] = true, -- End
  [XK_Shift_L] = true, [XK_Shift_R] = true,
  [XK_Control_L] = true, [XK_Control_R] = true,
}

local EXPANDED = "_asus_expanded"
local toggle_ascii = require("asus_shift").toggle_ascii
local list = require("asus_list")

-- Options tied to the expanded candidate list:
--   _linear       off: the list is vertical (weasel.custom.yaml, as in ASUS
--                 Smart Input), so Up/Down move the highlight (librime
--                 selector) and Left/Right change page (turn_page below).
--   _auto_commit  picking a candidate that completes the input commits it
--                 right away (librime Engine::OnSelect), as in ASUS Smart
--                 Input; Weasel discards uncommitted text when focus moves.
local function set_list_options(ctx, value)
  ctx:set_option("_linear", false)
  ctx:set_option("_auto_commit", value)
end

-- Left / Right, Page_Up / Page_Down in an open list: the first candidate of
-- the previous / next page. (The highlight is moved here, not by librime's
-- selector: asus_list.lua shows the text after the highlighted candidate.)
local function turn_page(ctx, env, step)
  local seg = ctx.composition:back()
  if not seg or not seg.menu then return end
  local page_size = env.engine.schema.page_size
  list.highlight(ctx, seg.selected_index - seg.selected_index % page_size + step * page_size)
end

local set_expanded

-- Pick candidate `index` of the open list. What is left of the input comes
-- next and its list stays open, as in ASUS Smart Input (a pick that completes
-- the input commits it, _auto_commit).
local function pick(ctx, index)
  ctx:select(index)
  if not (ctx:is_composing() and ctx:has_menu()) then set_expanded(ctx, false) end
end

set_expanded = function(ctx, value)
  list.clear(ctx)
  if ctx:get_option(EXPANDED) == value then return end
  ctx:set_option(EXPANDED, value)
  set_list_options(ctx, value)
  if ctx:is_composing() then
    ctx:refresh_non_confirmed_composition()
  end
end

local function init(env)
  local ctx = env.engine.context
  ctx:set_option(EXPANDED, false)
  set_list_options(ctx, false)
  -- Always start the next composition in compact mode, whether the previous
  -- one was committed or cleared (Esc, BackSpace to empty, app focus change).
  -- Otherwise digits of the next syllable would act as select keys.
  env.commit_conn = ctx.commit_notifier:connect(function(c)
    c:set_option(EXPANDED, false)
    set_list_options(c, false)
    -- English context for asus_lang.lua: was the last commit English?
    local text = c:get_commit_text() or ""
    -- (A word corrected on Space is committed with that space, asus_english.lua.)
    c:set_property("asus_en_ctx", text:match("[%a%d][%p]*%s?$") and "1" or "0")
    -- ...and its last word, for the suggestions (what usually follows it).
    c:set_property("asus_en_prev", (text:match("(%a[%a']*)%p*%s?$") or ""):lower())
    c:set_property("asus_final", "")
  end)
  env.update_conn = ctx.update_notifier:connect(function(c)
    if not c:is_composing() and (c:get_option(EXPANDED) or c:get_option("_linear")) then
      c:set_option(EXPANDED, false)
      set_list_options(c, false)
    end
  end)
end

local function fini(env)
  if env.commit_conn then env.commit_conn:disconnect() end
  if env.update_conn then env.update_conn:disconnect() end
end

local function func(key, env)
  local ctx = env.engine.context
  local code = key.keycode

  -- Mode switching (double-tap Shift: asus_shift.lua) ----------------------
  if code == XK_Shift_L or code == XK_Shift_R or key:release() then
    return kNoop
  end

  if code == XK_space and key:ctrl() and not key:alt() and not key:shift() then
    toggle_ascii(ctx)
    return kAccepted
  end

  -- English mode: only its composed word (asus_english.lua) is handled here
  -- (the expanded list of guesses).
  if ctx:get_option("ascii_mode") and not ctx:is_composing() then
    return kNoop
  end

  -- Shift+letter types a capital letter as English (asus_lang.lua treats any
  -- run with capitals as English), as in ASUS Smart Input.
  if key:shift() and not key:ctrl() and not key:alt()
      and code >= 0x41 and code <= 0x5a then  -- A-Z
    if ctx.input:sub(1, 1) ~= "`" then
      ctx:push_input(string.char(code))
      return kAccepted
    end
  end

  if not ctx:is_composing() then
    return kNoop
  end
  if ctx.input:sub(1, 1) == "`" then
    return kNoop  -- symbol keyboard (asus_symbols.lua) owns these keys
  end

  -- BackSpace deletes a whole character once its syllable is complete (ends
  -- with a tone key), like ASUS / Microsoft Bopomofo; an unfinished syllable
  -- and English letters still go one key at a time.
  if code == XK_BackSpace and key.modifier == 0 and ctx.caret_pos == #ctx.input then
    set_expanded(ctx, false)
    local seg = ctx.composition:back()
    if not (seg and (seg:has_tag("asus_en") or seg:has_tag("asus_stray"))) then
      local input = ctx.input
      for len = math.min(MAX_SYLLABLE, #input), 2, -1 do
        if zy.toned[input:sub(-len)] then
          ctx:pop_input(len)
          return kAccepted
        end
      end
    end
    return kNoop
  end

  -- Space after an English word commits everything typed so far followed by
  -- the space itself (so "I have a pencil" types naturally); after Chinese,
  -- Space stays the first-tone key.
  if code == XK_space and key.modifier == 0 and not ctx:get_option(EXPANDED) then
    local seg = ctx.composition:back()
    local cand = seg and seg:get_selected_candidate()
    if seg and seg:has_tag("asus_en") and cand and cand.type == "english" then
      -- ...unless the letters are a first-tone syllable typed one slip off.
      local typed = ctx.input:sub(seg.start + 1, seg._end)
      if seg._end == #ctx.input and not ctx:get_option("ascii_mode")
          and require("asus_lang").space_is_tone(typed, seg.start > 0,
                                                 seg.start == 0 and ctx:get_property("asus_en_ctx") == "1") then
        return kNoop
      end
      -- A misspelt word is corrected first: shown with the space, committed
      -- by the next key, taken back by BackSpace (asus_english.lua).
      if seg._end == #ctx.input and require("asus_english").correct_word(ctx, typed, " ") then
        return kAccepted
      end
      ctx:commit()
      env.engine:commit_text(" ")
      return kAccepted
    end
    -- A number in English text (iPhone 15 Pro): after an English word in
    -- the input, or as the whole input right after English was committed.
    if seg and seg:has_tag("asus_num") and cand and cand.type == "number" then
      local prev = nil
      for _, s in ipairs(ctx.composition:toSegmentation():get_segments()) do
        if s._end == seg.start and s._end > s.start then prev = s end
      end
      local english_before = prev and prev:has_tag("asus_en")
          or (seg.start == 0 and ctx:get_property("asus_en_ctx") == "1")
      if english_before then
        ctx:commit()
        env.engine:commit_text(" ")
        return kAccepted
      end
    end
  end

  -- Compact / expanded menu ----------------------------------------------
  local expanded = ctx:get_option(EXPANDED)
  if not expanded then
    if code == XK_Down and key.modifier == 0 and ctx:has_menu() then
      set_expanded(ctx, true)
      return kAccepted
    end
    if code == XK_Return and key.modifier == 0 then
      require("asus_lang").finalize(ctx)  -- digit keys at the end: a number now
    end
    return kNoop
  end

  if key.modifier == 0 and code >= 0x31 and code <= 0x39 then  -- 1-9
    local seg = ctx.composition:back()
    local page_size = env.engine.schema.page_size
    local page_start = seg.selected_index - seg.selected_index % page_size
    local index = page_start + (code - 0x31)
    if seg.menu:prepare(index + 1) > index then pick(ctx, index) end
    return kAccepted  -- never insert the digit as Zhuyin while expanded
  end
  if key.modifier == 0 and (code == XK_Left or code == XK_Right
                            or code == XK_Page_Up or code == XK_Page_Down) then
    turn_page(ctx, env, (code == XK_Right or code == XK_Page_Down) and 1 or -1)
    return kAccepted
  end
  if key.modifier == 0 and (code == XK_Up or code == XK_Down) then
    list.highlight(ctx, ctx.composition:back().selected_index + (code == XK_Down and 1 or -1))
    return kAccepted
  end
  if (code == XK_space or code == XK_Return) and key.modifier == 0 then
    -- select() (not confirm_current_selection) so Engine::OnSelect runs and
    -- _auto_commit can commit a completed input. Enter picks the highlighted
    -- candidate like Space (librime's default would commit the first one);
    -- it does not commit what is left: that could not be changed any more.
    pick(ctx, ctx.composition:back().selected_index)
    return kAccepted
  end
  if code == XK_Escape then
    set_expanded(ctx, false)
    return kAccepted
  end
  if not NAV_KEYS[code] then
    set_expanded(ctx, false)  -- typing resumes in compact mode
  end
  return kNoop
end

return { init = init, func = func, fini = fini, turn_page = turn_page }

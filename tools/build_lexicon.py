"""Generate the Taiwan supplement and personal dictionaries for terra_pinyin.asus.

  rime/terra_pinyin.tw.dict.yaml        from the Taiwan MOE dictionaries
  rime/terra_pinyin.personal.dict.yaml  from lexicon/personal_words.txt

Both are imported by rime/terra_pinyin.asus.dict.yaml (committed). Generated
files are not in git: the MOE data is CC BY-ND and personal words are private.

Taiwan supplement: only entries that change behaviour are written --
  alt     MOE reading not reachable from terra_pinyin char readings
          (晚上 ㄕㄤˋ, 衣服 ㄈㄨˊ, 咖啡 ㄎㄚ); weight = essay weight of the word
  prefer  MOE spelling loses to a non-MOE homophone in essay.txt
          (螢幕 588 < 熒幕 800); weight = best competitor + 1 -- unless the
          competitor is the commoner one in Taiwan text too (McBopomofo):
          請先 is no MOE entry but far commoner than 請仙 (also 沒人/媒人,
          跑到/跑道, 邁向/脈象)
  new     MOE word below the essay cut-off (min_phrase_weight); weight = --floor
Personal: weight = max(essay weight, --personal); symbols get weight 1.

Public package (DaoHui installer, tools/package_daohui_data.py): --public
writes both the Taiwan supplement and the personal dictionary as empty stubs
(the MOE data may not be redistributed, personal words are private) and only
the McBopomofo table has entries; use it with --out <dir>, never on rime/.

    python tools/build_lexicon.py [--floor N] [--personal N] [--no-tw] [--no-prefer]
    python tools/build_lexicon.py --public --out <dir>
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from rime_harness import weasel_root  # noqa: E402
from zhuyin import (essay_weights, keys_to_pinyin_map, moe_words,  # noqa: E402
                    reading_keys, terra_word_readings, zhuyin_to_pinyin)

ROOT = Path(__file__).resolve().parents[1]
RIME = ROOT / "rime"
PERSONAL_SRC = ROOT / "lexicon" / "personal_words.txt"

MIN_PHRASE_WEIGHT = 100  # terra_pinyin.dict.yaml
MAX_PHRASE_LENGTH = 7
HAN = re.compile(r"^[㐀-鿿豈-﫿]+$")

# Tuned on the dev set only (see reports/eval_history.jsonl).
DEFAULT_FLOOR = 100
DEFAULT_PERSONAL = 20000


def terra_char_reading_sets() -> dict[str, set[str]]:
    path = weasel_root() / "data" / "terra_pinyin.dict.yaml"
    out: dict[str, set[str]] = defaultdict(set)
    body = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if not body:
            body = line == "..."
            continue
        parts = line.split("\t")
        if len(parts) >= 2 and len(parts[0]) == 1:
            out[parts[0]].add(parts[1])
    return out


def write_dict(path: Path, name: str, rows: list[tuple[str, str, int]], note: str) -> None:
    head = [
        "# Rime dictionary",
        "# encoding: utf-8",
        f"# GENERATED by tools/build_lexicon.py -- do not edit. {note}",
        "---",
        f"name: {name}",
        'version: "1"',
        "sort: by_weight",
        "use_preset_vocabulary: false",
        "...",
        "",
    ]
    body = [f"{t}\t{c}\t{w}" for t, c, w in rows]
    path.write_text("\n".join(head + body) + "\n", encoding="utf-8")


def build_tw(floor: int, prefer: bool, mcb: dict[tuple[str, str], int] | None = None
             ) -> tuple[list[tuple[str, str, int]], dict[str, int]]:
    """mcb: McBopomofo weight per (word, pinyin reading), see build_mcb."""
    mcb = mcb or {}
    essay = essay_weights()
    moe = moe_words()
    char_sets = terra_char_reading_sets()
    terra_words = terra_word_readings()
    k2p = keys_to_pinyin_map()

    def default_reading(word: str) -> tuple[str, ...] | None:
        if word in terra_words:
            return tuple(terra_words[word].split())
        try:
            keys, _ = reading_keys(word, standard="terra")
        except KeyError:
            return None
        sylls = tuple(k2p.get(k) for k in keys)
        return None if None in sylls else sylls

    # Homophone index over essay words that terra_pinyin actually includes.
    index: dict[tuple[str, ...], list[tuple[str, int]]] = defaultdict(list)
    if prefer:
        for w, n in essay.items():
            if (n >= MIN_PHRASE_WEIGHT and 2 <= len(w) <= MAX_PHRASE_LENGTH
                    and w not in moe and HAN.match(w)):
                r = default_reading(w)
                if r:
                    index[r].append((w, n))

    rows: list[tuple[str, str, int]] = []
    stats = {"alt": 0, "prefer": 0, "new": 0, "not_preferred": 0}
    for word, sylls_z in moe.items():
        if not (2 <= len(word) <= MAX_PHRASE_LENGTH and HAN.match(word)):
            continue
        sylls = zhuyin_to_pinyin(" ".join(sylls_z))
        if not sylls:
            continue
        base = essay.get(word, 0)
        in_dict = base >= MIN_PHRASE_WEIGHT or word in terra_words
        reachable = all(p in char_sets.get(c, ()) for c, p in zip(word, sylls))
        if word in terra_words:
            reachable = reachable and terra_words[word].split() == sylls
        rival, competitor = max(index.get(tuple(sylls), ()), key=lambda wn: wn[1], default=("", 0))
        reading = " ".join(sylls)
        taiwan_rival = mcb.get((rival, reading), 0) > mcb.get((word, reading), 0)
        if prefer and competitor >= base and competitor > 0 and taiwan_rival:
            stats["not_preferred"] += 1
        if prefer and competitor >= base and competitor > 0 and not taiwan_rival:  # ties go to MOE spelling
            weight, kind = competitor + 1, "prefer"
        elif in_dict and not reachable:
            weight, kind = max(base, 1), "alt"
        elif not in_dict and floor > 0:
            weight, kind = floor, "new"
        else:
            continue
        rows.append((word, " ".join(sylls), weight))
        stats[kind] += 1
    return rows, stats


MCB_DIR = ROOT / "third_party" / "mcbopomofo"


def build_mcb() -> tuple[list[tuple[str, str, int]], dict]:
    """Taiwan phrase frequencies from McBopomofo (MIT): BPMFMappings + phrase.occ.

    Counts are rescaled to essay.txt's scale by the median essay/occ ratio of
    words frequent in both corpora, so the two weight sources are comparable.
    Explicit entries suppress essay.txt's (mainland) weight for the same word.
    """
    occ: dict[str, int] = {}
    for line in (MCB_DIR / "phrase.occ").read_text(encoding="utf-8").splitlines():
        word, _, n = line.rpartition(" ")
        if word and n.isdigit():
            occ[word] = int(n)
    essay = essay_weights()
    ratios = sorted(essay[w] / c for w, c in occ.items()
                    if len(w) >= 2 and c >= 50 and essay.get(w, 0) >= 50)
    scale = ratios[len(ratios) // 2]
    rows, seen, skipped = [], set(), 0
    for line in (MCB_DIR / "BPMFMappings.txt").read_text(encoding="utf-8").splitlines():
        word, _, zhuyin = line.partition(" ")
        if not (2 <= len(word) <= MAX_PHRASE_LENGTH and HAN.match(word)) or word not in occ:
            continue
        sylls = zhuyin_to_pinyin(zhuyin)
        if not sylls or len(sylls) != len(word):
            skipped += 1
            continue
        key = (word, " ".join(sylls))
        if key in seen:
            continue
        seen.add(key)
        rows.append((word, key[1], max(1, round(occ[word] * scale))))
    return rows, {"scale": round(scale, 2), "skipped": skipped}


def build_personal(personal_weight: int) -> tuple[list[tuple[str, str, int]], int]:
    if not PERSONAL_SRC.exists():
        return [], 0
    essay = essay_weights()
    k2p = keys_to_pinyin_map()
    rows, skipped = [], 0
    for line in PERSONAL_SRC.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        word, zhuyin, *_ = line.split("\t") + ["", ""]
        weight = max(essay.get(word, 0), personal_weight)
        sylls = None
        if zhuyin.startswith("@"):  # symbol typed by the reading of a word
            weight = 1
            try:
                keys, _ = reading_keys(zhuyin[1:])
                sylls = [k2p.get(k) for k in keys]
            except KeyError:
                pass
        elif zhuyin.strip():
            sylls = zhuyin_to_pinyin(zhuyin)
        else:
            try:
                keys, _ = reading_keys(word)
                sylls = [k2p.get(k) for k in keys]
            except KeyError:
                pass
        if not sylls or None in sylls:
            skipped += 1
            continue
        rows.append((word, " ".join(sylls), weight))
    return rows, skipped


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--floor", type=int, default=DEFAULT_FLOOR)
    ap.add_argument("--personal", type=int, default=DEFAULT_PERSONAL)
    ap.add_argument("--no-tw", action="store_true", help="write an empty Taiwan supplement")
    ap.add_argument("--no-prefer", action="store_true")
    ap.add_argument("--no-mcb", action="store_true", help="write an empty McBopomofo table")
    ap.add_argument("--out", type=Path, default=RIME)
    ap.add_argument("--no-personal", action="store_true", help="write an empty personal dictionary")
    ap.add_argument("--public", action="store_true",
                    help="public package: empty Taiwan MOE and personal stubs (implies --no-tw "
                         "--no-personal); needs --out")
    args = ap.parse_args()
    if args.public:
        if args.out.resolve() == RIME.resolve():
            ap.error("--public needs --out <dir>: rime/ is the live user folder")
        args.no_tw = args.no_personal = True

    mcb_rows, mcb_stats = ([], {}) if args.no_mcb or not MCB_DIR.exists() else build_mcb()
    mcb = {(w, r): n for w, r, n in mcb_rows}
    tw_rows, stats = ([], {}) if args.no_tw else build_tw(args.floor, not args.no_prefer, mcb)
    args.out.mkdir(parents=True, exist_ok=True)
    write_dict(args.out / "terra_pinyin.tw.dict.yaml", "terra_pinyin.tw", tw_rows,
               "Empty stub (public package): the Taiwan MOE supplement (CC BY-ND 3.0 TW) is not "
               "redistributed. A terra_pinyin.tw.dict.yaml in the user folder replaces this file."
               if args.public else
               "Source: Taiwan MOE dictionaries (CC BY-ND 3.0 TW), local use only.")
    p_rows, skipped = ([], 0) if args.no_personal else build_personal(args.personal)
    write_dict(args.out / "terra_pinyin.personal.dict.yaml", "terra_pinyin.personal", p_rows,
               "Empty stub (public package). A terra_pinyin.personal.dict.yaml with your own words "
               "in the user folder replaces this file."
               if args.public else "Source: lexicon/personal_words.txt (private).")
    write_dict(args.out / "terra_pinyin.mcb.dict.yaml", "terra_pinyin.mcb", mcb_rows,
               "Source: McBopomofo Source/Data (MIT), third_party/mcbopomofo.")
    print(f"tw: {len(tw_rows)} entries {stats}; personal: {len(p_rows)} entries, "
          f"{skipped} skipped (unknown reading); mcb: {len(mcb_rows)} entries {mcb_stats}")


if __name__ == "__main__":
    main()

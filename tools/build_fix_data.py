"""Write rime/lua/asus_fix_data.lua: every terra_pinyin syllable (as the
reverse lookup of the IME's dictionary spells it, e.g. "ni3", "de5") ->
the Dachen keys that type it ("su3", "2k7"). lua/asus_fix.lua uses it to
check that an AI correction still reads as the keys typed.

    python tools/build_fix_data.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from zhuyin import pinyin_to_keys, weasel_root  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "rime" / "lua" / "asus_fix_data.lua"


def syllables() -> set[str]:
    found: set[str] = set()
    paths = [weasel_root() / "data" / "terra_pinyin.dict.yaml", *sorted((ROOT / "rime").glob("*.dict.yaml"))]
    for path in paths:
        if not path.exists():
            continue
        body = False
        for line in path.read_text(encoding="utf-8").splitlines():
            if not body:
                body = line == "..."
                continue
            parts = line.split("\t")
            if len(parts) >= 2 and parts[1] and not line.startswith("#"):
                found.update(parts[1].split())
    return found


def main() -> None:
    table = {}
    for s in sorted(syllables()):
        try:
            table[s] = pinyin_to_keys(s)
        except (KeyError, ValueError):
            continue
    lines = ["-- GENERATED by tools/build_fix_data.py -- do not edit.",
             "-- terra_pinyin syllable -> Dachen keys (lua/asus_fix.lua).",
             "local M = {}", "M.keys = {"]
    lines += [f'  ["{s}"] = "{k}",' for s, k in table.items()
              if '"' not in s + k and "\\" not in s + k]
    lines += ["}", "return M", ""]
    OUT.write_bytes("\n".join(lines).encode("utf-8"))
    print(f"{len(table)} syllables -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
